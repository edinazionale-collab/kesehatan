alter table public.users enable row level security;
alter table public.master_data enable row level security;
alter table public.settings enable row level security;
alter table public.treatment enable row level security;
alter table public.moving enable row level security;
alter table public.pengambilan_obat enable row level security;
alter table public.penambahan_obat enable row level security;
alter table public.pen_trial enable row level security;
alter table public.salvage enable row level security;
alter table public.sync_log enable row level security;

